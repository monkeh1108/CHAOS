'use strict';
const fs=require('fs'),vm=require('vm');
const src=fs.readFileSync(__dirname+'/../../src/physics/low_contact.js','utf8');
const context=vm.createContext({console,Math});vm.runInContext(src+'\nthis.low=ChaosLowContact;',context);
const L=context.low;
const assert=(truth,msg)=>{if(!truth)throw Error('FAIL '+msg)};
const R={x:0,y:0,face:0,vx:6,vy:0,TAK:70,AGI:78,AWR:78,STR:78,balance:1,stam:1};
const D={x:.7,y:0,face:Math.PI,vx:-3,vy:0,action:{kind:'tackle-dive',time:.5},TAK:81};
assert(L.evaluate({...R,x:-.2},R,{...D,x:.9},D).hit,'low dive reaches running foot');
assert(!L.evaluate({...R,y:3}, {...R,y:3},D,D).hit,'wide dive misses');
assert(L.initiate(R,'hurdle'),'manual hurdle starts');
L.advance(R,.33);assert(L.height(R)>.75,'manual hurdle has real apex clearance');
assert(!L.evaluate({...R,x:-.2},R,{...D,x:.9},D).hit,'properly cleared low dive cannot trip runner');
assert(L.clearance(R,D),'only sufficiently high foot can clear low defender');
assert(L.bodyVulnerability(R)>1,'airborne player is less stable on genuine body hit');
L.advance(R,.31);assert(L.height(R)<.20,'landing foot becomes vulnerable again');
assert(L.evaluate({...R,x:-.2},R,{...D,x:.9},D).hit,'contact at landing can trip');
L.advance(R,.03);assert(!R.airState,'air state expires');
const G={...D,ground:{stage:'winded'},action:null};
assert(L.evaluate({...R,x:-.2},R,{...G,x:.9},G).hit,'grounded tackler may reach foot');
G.x=1.6;G.face=Math.PI;R.vx=6;R.vy=0;R.stam=1;R.balance=1;
assert(L.shouldAutoHop(R,G),'approaching a downed defender triggers small hop');
assert(L.initiate(R,'hop'),'automatic hop takes off');L.advance(R,.20);
assert(L.height(R)<.5 && L.bodyVulnerability(R)>1,'little hop is lower and vulnerable');
console.log('PASS: ankle contact, wide miss, timed hurdle clearance, landing exposure, grounded grab, natural hop, airborne vulnerability');
