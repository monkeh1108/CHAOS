'use strict';
const assert=require('assert'),fs=require('fs'),vm=require('vm');
const ctx=vm.createContext({});
for(const n of ['render/animation_policy','physics/dive_reach','physics/anatomy_hitboxes'])vm.runInContext(fs.readFileSync(__dirname+'/../../src/'+n+'.js','utf8'),ctx);
const R=vm.runInContext('ChaosDiveReach',ctx),A=vm.runInContext('AnatomyHitboxes',ctx);
const base={key:'SS',h:74,w:208,x:0,y:0,face:0};
const diving={...base,action:{kind:'tackle-dive',age:.30,time:.23,used:false}};
const d=R.pose(diving);assert(Math.abs(d.shoulder-2.35619449)<.02,'135 degree dive reach');
const hands=R.armPoints(diving,1,1);assert(hands.hand[2]>hands.elbow[2], 'dive wrist/hand elevated above elbow');
const noWrap={...base,intent:'pursue'},wrapping={...base,intent:'wrap'};
assert.equal(R.standingPose(noWrap),null,'ordinary run must not reach');
const w=R.standingPose(wrapping);assert(w && Math.abs(w.shoulder-Math.PI/2)<.001,'standing arms are 90 degrees');
const arm=R.armPoints(wrapping,1,1);assert(arm.wrist[0]>arm.elbow[0]+.4,'standing wrists reach forward');
const sample=A.sample(wrapping),non=A.sample(noWrap);
assert(sample.regions.length===15 && non.regions.length===15);
const fore=sample.regions.find(x=>x.region==='forearm'&&x.side===1),nonfore=non.regions.find(x=>x.region==='forearm'&&x.side===1);
assert(fore.a.x>nonfore.a.x,'standing wrap forearm must match visible forward reach');
assert(R.pose({...diving,action:{...diving.action,used:false}}).wrap===0,'dive does not wrap early');
console.log('PASS: 135 degree diving reach, 90 degree standing wrap, shared 15-region anatomy, nonwrapping movement unaffected');
