'use strict';
const assert = require('node:assert/strict');
const { AnatomyHitboxes: A } = require('../../src/physics/anatomy_hitboxes.js');
const { ChaosContactEvidence: E } = require('../../src/debug/contact_evidence.js');

const player=(key,team,x,y,h,w,face=0)=>({key,team,x,y,h,w,face,vx:0,vy:0,action:null,ground:null,pos:'RB',travel:0});
const rb=player('RB',0,0,0,71,211),cb=player('CB1',1,-4,0,72,190);
const rb1={...rb,x:0},cb1={...cb,x:4};
E.reset();E.setEnabled(true);E.setFullScan(true);
let result=E.scan([rb,cb],[rb1,cb1],.1,{all:true});
assert(result.length>0,'the sweep should find a crossing before final positions');
assert(E.history()[0].swept,'swept-only collision needs flag');
assert(E.history()[0].pair.includes('RB'));
assert(typeof E.history()[0].timeFraction==='number');
E.reset();
const cbMiss=player('CB1',1,-4,3.6,72,190),cbMiss1={...cbMiss,x:4};
assert(E.scan([rb,cbMiss],[rb1,cbMiss1],.1,{all:true}).length===0,'wide miss should not create contact');
const big=A.sample(player('LB',1,0,0,78,325)),small=A.sample(player('CB',1,0,0,68,170));
assert(big.regions.find(r=>r.region==='torso').r>small.regions.find(r=>r.region==='torso').r);
assert(big.dims.visualHeight>small.dims.visualHeight);
E.reset();E.scan([rb,cb],[rb1,cb1],.1,{all:true});
assert(E.history().length>0);E.reset();assert(E.history().length===0);
E.setEnabled(false);assert(E.scan([rb,cb],[rb1,cb1],.1,{all:true}).length===0);
console.log('PASS: cross-frame contact, miss, size variance, region metadata, reset and opt-out');
