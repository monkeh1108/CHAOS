'use strict';
const assert = require('node:assert/strict');
const { AnatomyHitboxes: A } = require('../../src/physics/anatomy_hitboxes.js');
const { ChaosContactOutcomes: C } = require('../../src/physics/contact_outcomes.js');

const contact=(a,b,penetration)=>({a,b,aSide:0,bSide:0,penetration});
const options={relativeSpeed:5,approachAngle:35};
assert.equal(C.classify([]).kind,'miss');
assert.equal(C.classify([contact('forearm','upperArm',.035)],options).kind,'light contact');
assert.equal(C.classify([contact('hand','pelvis',.09)],options).kind,'meaningful contact');
assert.equal(C.classify([contact('forearm','thigh',.18)],options).kind,'potential tackle');
assert.equal(C.classify([contact('torso','torso',.25)],options).kind,'potential tackle');
assert.notEqual(C.classify([contact('forearm','thigh',.18)],{...options,style:'wrap',grip:1.5,engagementAge:0}).kind,'guaranteed tackle','instant overlap cannot be guaranteed');
assert.equal(C.classify([contact('forearm','thigh',.18)],{...options,relativeSpeed:1.1,style:'wrap',grip:1.3,engagementAge:.50}).kind,'guaranteed tackle');
assert.notEqual(C.classify([contact('forearm','thigh',.18)],{...options,relativeSpeed:5,style:'wrap',grip:1.3,engagementAge:.50}).kind,'guaranteed tackle','fast escape cannot guarantee control');
assert.notEqual(C.classify([contact('forearm','thigh',.18)],{...options,relativeSpeed:1,style:'hit',grip:1.3,engagementAge:.50}).kind,'guaranteed tackle','hit stick is not automatically a secured wrap');
const p=(h,w)=>({h,w,x:0,y:0,face:0,pos:'DT',travel:0});
const dl=A.sample(p(78,320)),cb=A.sample(p(70,180));
assert(dl.regions.find(x=>x.region==='torso').r>cb.regions.find(x=>x.region==='torso').r);
assert(dl.regions.find(x=>x.region==='torso').r>.41);
assert.equal(dl.regions.length,15);
console.log('PASS: five contact outcomes, earned secured wrap, instant overlap and speed safeguards, distinct 15-region body sizes');
