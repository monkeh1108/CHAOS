const fs=require('fs'),vm=require('vm'),assert=require('assert');
const ctx=vm.createContext({});vm.runInContext(fs.readFileSync(__dirname+'/src/square_contact.js','utf8')+'\nthis.CSC=ChaosSquareContact',ctx);
const {CSC}=ctx;
let direct=CSC.classify({vx:5,vy:0},{vx:-4,vy:0},1,0);
assert(direct.square>.85,JSON.stringify(direct));
let glancing=CSC.classify({vx:4,vy:4},{vx:-2,vy:5},1,0);
assert(glancing.square<.1,JSON.stringify(glancing));
let chase=CSC.classify({vx:4,vy:0},{vx:5,vy:0},1,0);
assert(chase.square===0,JSON.stringify(chase));
assert(CSC.settleAge(.95,1.0,1.0,.65,null)>.15);
assert(CSC.settleAge(.95,1.0,1.0,.65,'truck')===0);
assert(CSC.settleAge(.95,.25,1.0,.65,null)===0);
console.log('PASS square collisions, glancing/chase, earned early completion and truck override');
